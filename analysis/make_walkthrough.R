# docs/model_walkthrough.md: every line of decision_model() at the medians of the inputs (v8, v9).
# As with make_variables() in the walnut template, the inputs are set in one environment -- here at their
# medians, taken from 20 000 draws of the input table -- and the body of decision_model() is run statement
# by statement; after each assignment its value is printed. The machine-downtime years (a chance event)
# are drawn with the run's seed and stated.
# Called at the end of atacora_DA_run.R. Standalone:  Rscript analysis/make_walkthrough.R

local({
  suppressPackageStartupMessages(library(decisionSupport))
  model_file <- "atacora_DA_model.R"
  est <- estimate_read_csv("data/estimates/atacora_DA_inputs_v8.csv")
  set.seed(20260927)
  invisible(capture.output(x <- suppressMessages(suppressWarnings(random(rho = est, n = 20000)))))
  med <- apply(x, 2, stats::median)
  env <- list2env(as.list(med), parent = globalenv())

  ex <- parse(model_file, keep.source = TRUE)
  src <- readLines(model_file, warn = FALSE)
  i_dm <- which(vapply(ex, function(e) is.call(e) && identical(e[[1]], as.name("<-")) &&
                         identical(e[[2]], as.name("decision_model")), logical(1)))
  body_expr <- ex[[i_dm]][[3]][[3]]
  sr <- attr(body_expr, "srcref")

  fmt <- function(v) {
    if (is.function(v)) return("(function, see the lines above)")
    if (is.list(v)) {
      num <- Filter(is.numeric, v)
      if (!length(num)) return(sprintf("list of %d", length(v)))
      show <- utils::head(names(num), 6)
      return(paste(vapply(show, function(k) {
        z <- num[[k]]
        if (length(z) > 1) sprintf("%s: sum %s (year 1 %s)", k, format(signif(sum(z), 5), big.mark = ","),
                                   format(signif(z[1], 5), big.mark = ","))
        else sprintf("%s = %s", k, format(signif(z, 5), big.mark = ","))
      }, character(1)), collapse = "; "))
    }
    if (is.numeric(v) && length(v) == 1) return(format(signif(v, 6), big.mark = ","))
    if (is.numeric(v)) {
      s <- paste(format(signif(v, 4), big.mark = ",", trim = TRUE), collapse = ", ")
      if (!is.null(names(v))) s <- paste(paste0(names(v), " = ", format(signif(v, 4), big.mark = ",", trim = TRUE)), collapse = ", ")
      return(s)
    }
    paste(format(v), collapse = ", ")
  }

  out <- c("# Walkthrough of `decision_model()` at the medians",
           "",
           sprintf("Generated by `analysis/make_walkthrough.R` from `%s` (%s). Every statement of", model_file, format(Sys.Date())),
           "`decision_model()` in order, with the value it produces when every input sits at its median",
           "(20 000 draws of `data/estimates/atacora_DA_inputs_v8.csv`, seed 20260927). Money in FCFA, discounted",
           "sums over the horizon unless a value is per year. The machine-downtime years are a chance event: they",
           "are drawn once here with the run's seed, as in every draw of the simulation.",
           "",
           "## Inputs at their medians",
           "",
           "| input | median | status | edge |",
           "|---|---:|---|---|")
  inp <- read.csv("data/estimates/atacora_DA_inputs_v8.csv", stringsAsFactors = FALSE)
  for (k in names(med)) out <- c(out, sprintf("| `%s` | %s | %s | %s |", k, format(signif(med[[k]], 4), big.mark = ","),
                                             inp$status[inp$variable == k], inp$edge[inp$variable == k]))
  out <- c(out, "", "## The body, statement by statement", "")

  set.seed(20260927)
  prev_end <- sr[[1]][1]                                                            # the line of the opening brace
  for (j in seq_along(body_expr)[-1]) {
    s <- sr[[j]]; l1 <- s[1]; l2 <- s[3]
    between <- src[seq_len(max(0, l1 - prev_end - 1)) + prev_end]
    comments <- trimws(sub("^\\s*#\\s?", "", between[grepl("^\\s*#", between)]))
    heads <- grepl("^([0-9]+\\.|\\([0-9]\\)) ", comments)
    for (k in seq_along(comments)) out <- c(out, if (heads[k]) c("", paste("###", comments[k]), "") else paste(">", comments[k]))
    e <- body_expr[[j]]
    val <- tryCatch(eval(e, envir = env), error = function(err) paste("ERROR:", conditionMessage(err)))
    out <- c(out, sprintf("Lines %d-%d:", l1, l2), "", "```r", src[l1:l2], "```", "")
    if (is.call(e) && identical(e[[1]], as.name("<-")) && is.name(e[[2]])) {
      out <- c(out, sprintf("= `%s`: %s", as.character(e[[2]]), fmt(get(as.character(e[[2]]), envir = env))), "")
    } else if (is.call(e) && identical(e[[1]], as.name("for"))) {
      out <- c(out, "(loop; its results are listed in the table below)", "")
    } else if (is.call(e) && identical(e[[1]], as.name("return"))) {
      out <- c(out, sprintf("= %d outputs.", length(unlist(val))), "")
    }
    prev_end <- l2
  }

  y <- unlist(eval(body_expr[[length(body_expr)]][[2]], envir = env))
  opts <- c("sq", "out", "up_std", "up_inc", "deep")
  out <- c(out, "## Net benefits at the medians (FCFA, discounted, against the status quo)", "",
           "| account | setting | sq | out | up_std | up_inc | deep |", "|---|---|---:|---:|---:|---:|---:|")
  for (a in c("G", "Wg", "H", "O", "comm", "Gself", "Ghire")) for (st in c("V0", "V1", "PREF"))
    out <- c(out, sprintf("| %s | %s | %s |", a, st, paste(vapply(opts, function(o)
      format(round(y[[paste("NB", a, o, st, sep = "_")]]), big.mark = ","), character(1)), collapse = " | ")))
  out <- c(out, "", "One draw at the medians is not the median of the draws; the key findings report the draws.")
  writeLines(out, "docs/model_walkthrough.md")
})
